-- =====================================================================
-- BookInn — Phase 1 migration 0001: final 3NF schema (SRS §4.2 3NF,
-- §4.3 Relational Schema, §4.4 Data Dictionary).
--
-- All 11 entities live in a dedicated Postgres schema "bookinn" so they
-- never collide with the legacy PHP app's tables (staff, customer, room,
-- ...) that already exist in the same Supabase database's "public" schema.
--
-- Conventions
--   * Column names/types follow the data dictionary exactly (lower-cased,
--     since unquoted Postgres identifiers fold to lower case).
--   * "enum" columns use native Postgres ENUM types with the dictionary's
--     allowed values.
--   * int surrogate PKs use GENERATED BY DEFAULT AS IDENTITY, starting at
--     the numbering used in the SRS sample data (1001, 5001, 9001, 10001).
--   * EVERY foreign key is ON DELETE RESTRICT / ON UPDATE RESTRICT.
--     No ON DELETE CASCADE anywhere, so deleting a parent can never wipe
--     reservation, payment, receipt, cancellation or audit history.
--   * Constraints marked [BR] enforce a documented SRS business rule
--     (§3.3) at the database level; they do not add columns.
-- =====================================================================

CREATE SCHEMA IF NOT EXISTS bookinn;

-- ---------------------------------------------------------------------
-- Enum types (allowed values copied verbatim from the data dictionary)
-- ---------------------------------------------------------------------
CREATE TYPE bookinn.booking_status_t AS ENUM ('Booked', 'Completed', 'Cancelled');
CREATE TYPE bookinn.room_type_t      AS ENUM ('Standard', 'Deluxe');
CREATE TYPE bookinn.room_view_t      AS ENUM ('Ocean View', 'City View', 'Garden View', 'Pool View');
CREATE TYPE bookinn.pay_method_t     AS ENUM ('Cash', 'Bank', 'Card', 'Digital Wallet');
CREATE TYPE bookinn.discount_type_t  AS ENUM ('12% Discount', 'Free Night', 'NONE');
CREATE TYPE bookinn.cancelled_by_t   AS ENUM ('Customer', 'Staff');
CREATE TYPE bookinn.staff_role_t     AS ENUM ('Front Desk', 'Finance', 'Database Administrator');
CREATE TYPE bookinn.audit_action_t   AS ENUM ('UPDATE', 'INSERT', 'DELETE');
CREATE TYPE bookinn.aff_tab_t        AS ENUM (
    'STAFF', 'CANCELLATION', 'RESERVATION', 'RESERVATION_ROOM', 'RECEIPT',
    'ROOM', 'ROOM_DETAILS', 'CUSTOMER', 'LOYALTY_ACC', 'PAYMENT'
);

-- ---------------------------------------------------------------------
-- CUSTOMER
-- ---------------------------------------------------------------------
CREATE TABLE bookinn.customer (
    cus_id      int GENERATED BY DEFAULT AS IDENTITY (START WITH 1001) PRIMARY KEY,
    cus_name    varchar(100) NOT NULL,
    cus_email   varchar(100) NOT NULL,        -- [BR] email mandatory (receipts)
    cus_mobile  varchar(12)  NOT NULL,        -- text keeps leading zeros
    CONSTRAINT customer_email_uq    UNIQUE (cus_email),
    CONSTRAINT customer_name_chk    CHECK (btrim(cus_name) <> ''),
    CONSTRAINT customer_email_chk   CHECK (cus_email ~ '^[^@\s]+@[^@\s]+\.[^@\s]+$'),
    CONSTRAINT customer_mobile_chk  CHECK (cus_mobile ~ '^\+?[0-9]{7,11}$')
);

-- ---------------------------------------------------------------------
-- LOYALTY_ACC
-- ---------------------------------------------------------------------
CREATE TABLE bookinn.loyalty_acc (
    lyl_id     int GENERATED BY DEFAULT AS IDENTITY (START WITH 5001) PRIMARY KEY,
    cus_id     int NOT NULL
               REFERENCES bookinn.customer (cus_id) ON DELETE RESTRICT ON UPDATE RESTRICT,
    total_pts  int NOT NULL DEFAULT 0,
    CONSTRAINT loyalty_acc_cus_uq   UNIQUE (cus_id),          -- [BR] one account per guest
    CONSTRAINT loyalty_acc_pts_chk  CHECK (total_pts >= 0)
);

-- ---------------------------------------------------------------------
-- ROOM_DETAILS (room type catalogue)
-- ---------------------------------------------------------------------
CREATE TABLE bookinn.room_details (
    room_type_id  varchar(4) PRIMARY KEY,
    room_type     bookinn.room_type_t NOT NULL,
    room_price    decimal(8, 2)       NOT NULL,               -- per night
    room_view     bookinn.room_view_t NOT NULL,               -- [BR] type, view, price required
    CONSTRAINT room_details_id_chk     CHECK (room_type_id ~ '^[A-Z0-9]{1,4}$'),
    CONSTRAINT room_details_price_chk  CHECK (room_price > 0)
);

-- ---------------------------------------------------------------------
-- ROOM
-- ---------------------------------------------------------------------
CREATE TABLE bookinn.room (
    room_no       int PRIMARY KEY,
    room_type_id  varchar(4) NOT NULL
                  REFERENCES bookinn.room_details (room_type_id) ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT room_no_chk CHECK (room_no > 0)
);

-- ---------------------------------------------------------------------
-- RESERVATION
-- ---------------------------------------------------------------------
CREATE TABLE bookinn.reservation (
    res_id          int GENERATED BY DEFAULT AS IDENTITY (START WITH 1001) PRIMARY KEY,
    cus_id          int NOT NULL
                    REFERENCES bookinn.customer (cus_id) ON DELETE RESTRICT ON UPDATE RESTRICT,
    booking_status  bookinn.booking_status_t NOT NULL DEFAULT 'Booked'
);

-- ---------------------------------------------------------------------
-- RESERVATION_ROOM
-- Double-booking prevention (FR-16) needs RESERVATION.booking_status, which
-- lives in another table, so it cannot be a single-table EXCLUDE constraint.
-- It is enforced transactionally by the app (row lock on ROOM + overlap query).
-- ---------------------------------------------------------------------
CREATE TABLE bookinn.reservation_room (
    res_room_id     int GENERATED BY DEFAULT AS IDENTITY (START WITH 10001) PRIMARY KEY,
    res_id          int NOT NULL
                    REFERENCES bookinn.reservation (res_id) ON DELETE RESTRICT ON UPDATE RESTRICT,
    room_no         int NOT NULL
                    REFERENCES bookinn.room (room_no) ON DELETE RESTRICT ON UPDATE RESTRICT,
    check_in_date   date NOT NULL,
    check_out_date  date NOT NULL,
    CONSTRAINT reservation_room_dates_chk CHECK (check_out_date > check_in_date)  -- "Must be after check-in"
);
CREATE INDEX reservation_room_res_idx  ON bookinn.reservation_room (res_id);
CREATE INDEX reservation_room_room_idx ON bookinn.reservation_room (room_no, check_in_date, check_out_date);

-- ---------------------------------------------------------------------
-- PAYMENT
-- ---------------------------------------------------------------------
CREATE TABLE bookinn.payment (
    pay_id         int GENERATED BY DEFAULT AS IDENTITY (START WITH 1001) PRIMARY KEY,
    res_id         int NOT NULL
                   REFERENCES bookinn.reservation (res_id) ON DELETE RESTRICT ON UPDATE RESTRICT,
    pay_method     bookinn.pay_method_t    NOT NULL,
    pay_date       date                    NOT NULL,
    pay_amt        decimal(8, 2)           NOT NULL,
    pts_earn       int                     NOT NULL DEFAULT 0,
    pts_spend      int                     NOT NULL DEFAULT 0,
    discount_type  bookinn.discount_type_t NOT NULL DEFAULT 'NONE',
    CONSTRAINT payment_res_uq       UNIQUE (res_id),                 -- [BR] one-time payment per reservation
    CONSTRAINT payment_amt_chk      CHECK (pay_amt >= 0),            -- 0 allowed (free-night edge case)
    CONSTRAINT payment_pts_chk      CHECK (pts_earn >= 0 AND pts_spend >= 0),
    CONSTRAINT payment_earn_xor_spend_chk
        CHECK (pts_earn = 0 OR pts_spend = 0),                        -- [BR] cannot earn and spend at once
    CONSTRAINT payment_discount_pts_chk CHECK (                       -- [BR] 100 pts = 12%, 250 pts = free night
        (discount_type = 'NONE'         AND pts_spend = 0)   OR
        (discount_type = '12% Discount' AND pts_spend = 100) OR
        (discount_type = 'Free Night'   AND pts_spend = 250)
    )
);

-- ---------------------------------------------------------------------
-- RECEIPT
-- ---------------------------------------------------------------------
CREATE TABLE bookinn.receipt (
    rct_no  int GENERATED BY DEFAULT AS IDENTITY (START WITH 1001) PRIMARY KEY,
    pay_id  int NOT NULL
            REFERENCES bookinn.payment (pay_id) ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT receipt_pay_uq UNIQUE (pay_id)                          -- [BR] one receipt per payment
);

-- ---------------------------------------------------------------------
-- CANCELLATION
-- ---------------------------------------------------------------------
CREATE TABLE bookinn.cancellation (
    cancel_id     int GENERATED BY DEFAULT AS IDENTITY (START WITH 9001) PRIMARY KEY,
    res_id        int NOT NULL
                  REFERENCES bookinn.reservation (res_id) ON DELETE RESTRICT ON UPDATE RESTRICT,
    cancel_date   date NOT NULL,
    cancelled_by  bookinn.cancelled_by_t NOT NULL,
    CONSTRAINT cancellation_res_uq UNIQUE (res_id)                     -- a reservation is cancelled at most once
);

-- ---------------------------------------------------------------------
-- STAFF
-- pass stores a bcrypt hash only (never plaintext).
-- ---------------------------------------------------------------------
CREATE TABLE bookinn.staff (
    staff_id  int GENERATED BY DEFAULT AS IDENTITY (START WITH 1001) PRIMARY KEY,
    pass      varchar(255) NOT NULL,
    u_name    varchar(30)  NOT NULL,
    name      varchar(100) NOT NULL,
    role      bookinn.staff_role_t NOT NULL,
    CONSTRAINT staff_u_name_uq   UNIQUE (u_name),                      -- [BR] unique credentials
    CONSTRAINT staff_u_name_chk  CHECK (u_name ~ '^[A-Za-z0-9._-]{3,30}$'),
    CONSTRAINT staff_pass_hash_chk CHECK (pass ~ '^\$2[aby]\$[0-9]{2}\$.{53}$')  -- must be a bcrypt hash
);

-- ---------------------------------------------------------------------
-- AUDIT_TRAIL (append-only; written by the application on every mutation)
-- ---------------------------------------------------------------------
CREATE TABLE bookinn.audit_trail (
    audit_id     int GENERATED BY DEFAULT AS IDENTITY (START WITH 1001) PRIMARY KEY,
    staff_id     int NOT NULL
                 REFERENCES bookinn.staff (staff_id) ON DELETE RESTRICT ON UPDATE RESTRICT,
    action       bookinn.audit_action_t NOT NULL,
    aff_tab      bookinn.aff_tab_t      NOT NULL,
    rec_id       int,                     -- NULL only for ROOM_DETAILS (varchar PK, see README)
    "timestamp"  timestamp              NOT NULL DEFAULT now(),
    old_data     varchar(100),
    new_data     varchar(100)
);
CREATE INDEX audit_trail_tab_rec_idx ON bookinn.audit_trail (aff_tab, rec_id);

-- The audit trail is history: block UPDATE/DELETE at the database level so
-- it stays trustworthy even if application code is bypassed.
CREATE FUNCTION bookinn.audit_trail_immutable() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    RAISE EXCEPTION 'AUDIT_TRAIL is append-only (% not allowed)', TG_OP
        USING ERRCODE = 'insufficient_privilege';
END;
$$;

CREATE TRIGGER audit_trail_no_update_delete
    BEFORE UPDATE OR DELETE ON bookinn.audit_trail
    FOR EACH ROW EXECUTE FUNCTION bookinn.audit_trail_immutable();
